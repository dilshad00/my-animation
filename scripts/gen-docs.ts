/**
 * Regenerates docs/LIBRARY.md from the live registries.
 *   npm run docs
 */
import fs from "node:fs";
import path from "node:path";
import { PRESETS } from "../src/components/characters/presets";
import { CATALOG, describe } from "../src/utils/catalog";
import { LOCAL_SFX, REMOTE_SFX } from "../src/utils/sfx";

const d = describe();
const table = (rows: Record<string, string>) =>
  "| Name | Notes |\n|---|---|\n" + Object.entries(rows).map(([k, v]) => `| \`${k}\` | ${v.replace(/\|/g, "\\|")} |`).join("\n");

const md = `# Library reference

_Auto-generated by \`npm run docs\` — do not edit by hand._

## Environments (\`scene.environment.type\`)
Every environment supports \`time\`: \`dawn | day | sunset | night\` and \`weather\`: \`clear | cloudy | rain | storm | snow | fog | wind\`.

${table(d.environments)}

## Characters (\`"kind": "character", "who": …\`)

| id | Name | Body | Hair | Outfit |
|---|---|---|---|---|
${Object.entries(PRESETS)
  .map(([k, v]) => `| \`${k}\` | ${v.name} | ${v.body} | ${v.hair} | ${v.outfit} |`)
  .join("\n")}

**Actions** (\`actions: [{ "t": …, "do": … }]\`): ${CATALOG.actions.map((a) => `\`${a}\``).join(", ")}

**Expressions** (\`expressions: [{ "t": …, "is": … }]\`): ${CATALOG.expressions.map((a) => `\`${a}\``).join(", ")}

**Custom cast** (in \`storyboard.json → cast\`): body \`slim | average | athletic | heavy | child | elder\`,
hair \`short | side | spiky | bob | long | ponytail | bun | curly | afro | bald\`,
outfit \`tshirt | hoodie | shirt | suit | dress | labcoat | jacket | spacesuit | robe | overalls\`,
colours \`skin, hairColor, top, bottom, shoes, accent, eyeColor\`, plus \`glasses\`, \`beard\`, and \`preset\` to start from a built-in.

## Objects (\`"kind": "object", "type": …\`)
${table(d.objects)}

## Diagrams (\`"kind": "diagram", "type": …\`)
${table(d.diagrams)}

## Effects (\`"kind": "effect", "type": …\`)
${table(d.effects)}

## Sound effects (\`scene.sfx[].src\`, \`transition.sfx\`)
Local (generated, offline): ${LOCAL_SFX.map((s) => `\`${s}\``).join(", ")}
Remote (free, needs internet while rendering): ${Object.keys(REMOTE_SFX).map((s) => `\`${s}\``).join(", ")}
Or any file path inside \`public/\`.
`;
const out = path.resolve(import.meta.dirname, "..", "docs", "LIBRARY.md");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
console.log("Wrote", path.relative(process.cwd(), out));
