/**
 * Scans projects/<id>/storyboard.json and writes src/projects.generated.ts so
 * every project appears as a composition in Remotion Studio. It also copies
 * projects/<id>/narration.mp3 to public/audio/<id>/ where Remotion can play it.
 * Runs automatically before dev, validate, storyboard, render and after transcribe.
 *
 *   npm run sync
 */
import fs from "node:fs";
import path from "node:path";
import { captionsFile, findNarration, listProjectIds, PUBLIC_DIR, rel, ROOT, servedNarration } from "./lib/files";

const out = path.join(ROOT, "src", "projects.generated.ts");
const ids = listProjectIds();

const bad = ids.filter((id) => !/^[a-zA-Z0-9-]+$/.test(id));
if (bad.length) {
  console.error(`Project folder names may only contain letters, numbers and dashes: ${bad.join(", ")}`);
  process.exit(1);
}

const imports: string[] = [];
const entries: string[] = [];
const notes: string[] = [];
ids.forEach((id, i) => {
  imports.push(`import s${i} from "../projects/${id}/storyboard.json";`);
  const cap = captionsFile(id);
  const hasCaptions = fs.existsSync(cap);
  if (hasCaptions) imports.push(`import c${i} from "../projects/${id}/captions.json";`);

  const voice = findNarration(id);
  let served: string | null = null;
  if (voice && hasCaptions) {
    served = servedNarration(id, voice);
    const dest = path.join(PUBLIC_DIR, served);
    const a = fs.statSync(voice);
    const b = fs.existsSync(dest) ? fs.statSync(dest) : null;
    if (!b || b.size !== a.size || b.mtimeMs < a.mtimeMs) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(voice, dest);
    }
    if (a.mtimeMs > fs.statSync(cap).mtimeMs + 1000) notes.push(`${id}: ${rel(voice)} is newer than captions.json – run "npm run transcribe -- ${id}" if you re-recorded it.`);
  } else if (voice) {
    notes.push(`${id}: ${rel(voice)} found but not transcribed yet – run "npm run transcribe -- ${id}". Previewing with estimated timing until then.`);
  }
  entries.push(`  ${JSON.stringify(id)}: { storyboard: s${i}, captions: ${hasCaptions ? `c${i}` : "null"}, narration: ${JSON.stringify(served)} },`);
});

const next = [
  "// AUTO-GENERATED by scripts/sync-projects.ts – do not edit by hand.",
  ...imports,
  "",
  "export type ProjectEntry = {",
  "  /** contents of projects/<id>/storyboard.json */",
  "  storyboard: unknown;",
  "  /** contents of projects/<id>/captions.json (word timestamps), if transcribed */",
  "  captions: unknown;",
  "  /** narration file inside public/, only set once it has been transcribed */",
  "  narration: string | null;",
  "};",
  "",
  "export const PROJECTS: Record<string, ProjectEntry> = {",
  ...entries,
  "};",
  "",
  `export const PROJECT_IDS: string[] = ${JSON.stringify(ids)};`,
  "",
].join("\n");
const prev = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
if (prev !== next) fs.writeFileSync(out, next);
console.log(`Projects: ${ids.length ? ids.join(", ") : "(none)"}`);
notes.forEach((n) => console.log("ℹ " + n));
