/**
 * Aligns script.md with the transcribed narration (captions.json) and lists
 * every sentence with its real start/end time. This is the basis for
 * planning scenes from the actual audio rather than estimates.
 *
 *   npm run timing -- <project-id>
 *
 * Output: projects/<id>/timing.md (+ a summary in the terminal)
 */
import fs from "node:fs";
import path from "node:path";
import { alignWords, captionsToWords, normalizeWord, splitWords, type Word } from "../src/utils/narration";
import { normalizeCaptionsJson } from "../src/utils/project";
import { captionsFile, findNarration, parseScript, projectDir, readJson, rel, scriptFile } from "./lib/files";

const id = process.argv.slice(2).find((a) => !a.startsWith("--"));
if (!id) {
  console.error("Usage: npm run timing -- <project-id>");
  process.exit(1);
}
for (const f of [scriptFile(id), captionsFile(id)]) {
  if (!fs.existsSync(f)) {
    console.error(`✗ ${rel(f)} not found${f.endsWith("captions.json") ? ` – run npm run transcribe -- ${id}` : ""}`);
    process.exit(1);
  }
}

const { title, scenes: sections } = parseScript(fs.readFileSync(scriptFile(id), "utf8"));
const heard: Word[] = captionsToWords(normalizeCaptionsJson(readJson(captionsFile(id))));

// script words, remembering which section and sentence each belongs to
type W = { text: string; section: number; sentence: number };
const words: W[] = [];
const sentences: { section: number; text: string }[] = [];
sections.forEach((s, si) => {
  const parts = s.narration.match(/[^.!?…]+(?:[.!?…]+["”’)]*|$)/g) ?? [s.narration];
  for (const p of parts.map((x) => x.trim()).filter(Boolean)) {
    const k = sentences.length;
    sentences.push({ section: si, text: p });
    for (const w of splitWords(p)) words.push({ text: w, section: si, sentence: k });
  }
});

const map = alignWords(
  words.map((w) => normalizeWord(w.text)),
  heard.map((h) => normalizeWord(h.text)),
);
const matched = map.filter((m) => m >= 0).length;
const ratio = matched / words.length;

// time of each sentence = first/last matched word inside it
const fmt = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, "0")}`;
const sentTimes = sentences.map((_, k) => {
  const idx = words.map((w, i) => (w.sentence === k && map[i] >= 0 ? map[i] : -1)).filter((x) => x >= 0);
  return idx.length ? { start: heard[Math.min(...idx)].start, end: heard[Math.max(...idx)].end, matched: idx.length } : null;
});
// fill unmatched sentences between neighbours
sentTimes.forEach((t, k) => {
  if (t) return;
  const prev = sentTimes.slice(0, k).reverse().find(Boolean);
  const next = sentTimes.slice(k + 1).find(Boolean);
  sentTimes[k] = { start: prev?.end ?? 0, end: next?.start ?? (prev?.end ?? 0) + 2, matched: 0 };
});

const voice = findNarration(id);
const audioEnd = heard.length ? heard[heard.length - 1].end : 0;
const lines: string[] = [];
lines.push(`# Narration timing: ${title ?? id}`, "");
lines.push(`_Generated by \`npm run timing -- ${id}\` from ${voice ? rel(voice) : "narration"} + captions.json._`, "");
lines.push(`- Last spoken word ends at **${fmt(audioEnd)}**`);
lines.push(`- Script words matched in the recording: **${matched}/${words.length} (${Math.round(ratio * 100)}%)**`, "");
let lastSection = -1;
sentences.forEach((s, k) => {
  const t = sentTimes[k]!;
  if (s.section !== lastSection) {
    lastSection = s.section;
    const secSent = sentences.map((x, i) => (x.section === s.section ? i : -1)).filter((i) => i >= 0);
    const a = sentTimes[secSent[0]]!.start;
    const b = sentTimes[secSent[secSent.length - 1]]!.end;
    lines.push("", `## ${sections[s.section].name ?? `Section ${s.section + 1}`}  (${fmt(a)} → ${fmt(b)}, ${(b - a).toFixed(1)}s)`, "");
    lines.push("| # | Start | End | Sentence |", "|---|---|---|---|");
  }
  const gapBefore = k > 0 ? t.start - sentTimes[k - 1]!.end : t.start;
  lines.push(`| ${k + 1} | ${fmt(t.start)} | ${fmt(t.end)} | ${s.text.replace(/\|/g, "\\|")}${t.matched === 0 ? " ⚠ not found in audio" : ""}${gapBefore > 1.2 ? ` _(pause ${gapBefore.toFixed(1)}s before)_` : ""} |`);
});

// words that were spoken but are not in the script (ad-libs / changed lines)
const used = new Set(map.filter((m) => m >= 0));
const extra: string[] = [];
let run: string[] = [];
heard.forEach((h, i) => {
  if (!used.has(i)) run.push(h.text);
  else if (run.length) {
    if (run.length >= 3) extra.push(`${fmt(heard[i - run.length].start)}: "${run.join(" ")}"`);
    run = [];
  }
});
if (extra.length) lines.push("", "## Spoken but not in the script (3+ words)", "", ...extra.map((e) => `- ${e}`));

const out = path.join(projectDir(id), "timing.md");
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`${title ?? id}: ${sentences.length} sentences, audio ends ${fmt(audioEnd)}, ${Math.round(ratio * 100)}% of script words matched`);
if (extra.length) console.log(`⚠ ${extra.length} passage(s) spoken that are not in the script – see timing.md`);
console.log(`✓ ${rel(out)}`);
