"""Shorts data generator: projects/<id>/{words.json,cues.json} -> src/shorts/<module>/data.ts
python scripts/shorts/gen_data.py <project-id> <module-dir> [tail_frames=55]
- cues.json: {"key": "phrase"} searched in order (each search starts after the previous hit).
- Captions: Shorts style, 1-3 words; break at punctuation, pauses > 0.25 s, or 3 words / 1.2 s.
- VOX: per-frame voice activity string ("1" = speaking) for music ducking."""
import json, re, sys

pid, mod = sys.argv[1], sys.argv[2]
TAIL = int(sys.argv[3]) if len(sys.argv) > 3 else 55
FPS = 30
W = [w for w in json.load(open(f"projects/{pid}/words.json", encoding="utf-8")) if w["w"].strip()]
for i in range(len(W) - 1, 0, -1):  # whisper splits "50 %" -> merge
    if W[i]["w"] in ("%", "%.", "%,"):
        W[i - 1]["w"] += W[i]["w"]; W[i - 1]["e"] = W[i]["e"]; del W[i]
key = lambda t: re.sub(r"[^a-z0-9%]", "", t.lower())
K = [key(w["w"]) for w in W]
cue, pos = {}, 0
for k, ph in json.load(open(f"projects/{pid}/cues.json", encoding="utf-8")).items():
    toks = [key(t) for t in ph.split()]
    for i in range(pos, len(K)):
        if [re.sub("%", "", x) for x in K[i:i + len(toks)]] == [re.sub("%", "", t) for t in toks]:
            cue[k] = round(W[i]["s"] * FPS); pos = i + 1; break
    else:
        raise SystemExit(f"cue not found: {k} '{ph}' after word {pos}: {' '.join(K[pos:pos + 10])}")
caps, cur = [], []
for i, w in enumerate(W):
    cur.append(w)
    nxt = W[i + 1] if i + 1 < len(W) else None
    if (w["w"][-1] in ".?!,;:" or nxt is None or nxt["s"] - w["e"] > 0.25 or len(cur) >= 3
            or (nxt and nxt["e"] - cur[0]["s"] > 1.2)):
        caps.append([round(cur[0]["s"] * FPS), round((nxt["s"] if nxt else w["e"] + 0.3) * FPS), [[x["w"], round(x["s"] * FPS)] for x in cur]])
        cur = []
VO = round(W[-1]["e"] * FPS)
TOTAL = VO + TAIL
vox = ["0"] * (TOTAL + 1)
for w in W:
    for f in range(round(w["s"] * FPS) - 3, round(w["e"] * FPS) + 6):
        if 0 <= f <= TOTAL: vox[f] = "1"
out = f"src/shorts/{mod}/data.ts"
with open(out, "w", encoding="utf-8") as o:
    o.write(f"// generated by scripts/shorts/gen_data.py {pid} {mod} — do not edit\n")
    o.write(f"export const TOTAL_FRAMES = {TOTAL};\nexport const VO_FRAMES = {VO};\n")
    o.write(f"export const CUE: Record<string, number> = {json.dumps(cue)};\n")
    o.write(f"export const CAPTIONS: [number, number, [string, number][]][] = {json.dumps(caps, ensure_ascii=False)};\n")
    o.write(f'export const VOX = "{"".join(vox)}";\n')
print(f"{out}: {len(cue)} cues, {len(caps)} captions, {TOTAL} frames ({TOTAL / FPS:.1f}s)")
print(" ".join(f"{k}={v}" for k, v in cue.items()))
