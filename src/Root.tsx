import { Composition, Folder } from "remotion";
import { ActionGallery, CastGallery } from "./compositions/CharacterGallery";
import {
  DIAGRAM_GALLERY_FRAMES,
  DiagramGallery,
  EffectGallery,
  ENV_GALLERY_FRAMES,
  EnvironmentGallery,
  ObjectGallery,
} from "./compositions/Galleries";
import { calculateVideoMetadata, VideoComposition } from "./compositions/VideoComposition";
import { PROJECT_IDS } from "./projects.generated";
import { Thumbnail } from "./compositions/Thumbnail";
import { AnimeAssets, type AnimeSheet } from "./compositions/AnimeAssets";
import { ANIME_DEMO_FRAMES, AnimeDemo } from "./compositions/AnimeDemo";
import { UG_DEMO_FRAMES, UgDemo } from "./ug/UgDemo";
import { UG001_FRAMES, UG001_SHEET_FRAMES, UgFull, UgSheet } from "./ug/UgFull";

/**
 * Every folder in projects/<id>/ (with a storyboard.json) becomes a composition "<id>".
 * (The list is generated by `npm run sync`, which runs automatically
 * before `npm run dev` / `npm run render`.)
 */
export const RemotionRoot: React.FC = () => {
  return (
    <>
      <Folder name="Videos">
        {PROJECT_IDS.map((id) => (
          <Composition
            key={id}
            id={id}
            component={VideoComposition}
            durationInFrames={300}
            fps={30}
            width={1920}
            height={1080}
            defaultProps={{ projectId: id }}
            calculateMetadata={calculateVideoMetadata}
          />
        ))}
      </Folder>
      {/* Rendered by `npm run thumbnails -- <id>` with a spec from projects/<id>/thumbnails.json */}
      <Composition id="Thumbnail" component={Thumbnail} durationInFrames={300} fps={30} width={1920} height={1080} defaultProps={{}} />
      <Folder name="Style-Experiments">
        <Composition id="Anime-Demo" component={AnimeDemo} durationInFrames={ANIME_DEMO_FRAMES} fps={30} width={1920} height={1080} />
        <Composition id="Anime-Assets" component={AnimeAssets} durationInFrames={1} fps={30} width={1920} height={1080} defaultProps={{ sheet: "character" as AnimeSheet }} />
      </Folder>
      <Folder name="UnknownGamer">
        <Composition id="UG-Demo" component={UgDemo} durationInFrames={UG_DEMO_FRAMES} fps={30} width={1920} height={1080} />
        <Composition id="UG-001" component={UgFull} durationInFrames={UG001_FRAMES} fps={30} width={1920} height={1080} />
        <Composition id="UG-001-Sheet" component={UgSheet} durationInFrames={UG001_SHEET_FRAMES} fps={30} width={1920} height={1080} />
      </Folder>
      <Folder name="Library-Tests">
        <Composition id="Test-Cast" component={CastGallery} durationInFrames={240} fps={30} width={1920} height={1080} />
        <Composition id="Test-Actions" component={ActionGallery} durationInFrames={240} fps={30} width={1920} height={1080} />
        <Composition id="Test-Environments" component={EnvironmentGallery} durationInFrames={ENV_GALLERY_FRAMES} fps={30} width={1920} height={1080} />
        <Composition id="Test-Objects-1" component={ObjectGallery} defaultProps={{ page: 0 }} durationInFrames={180} fps={30} width={1920} height={1080} />
        <Composition id="Test-Objects-2" component={ObjectGallery} defaultProps={{ page: 1 }} durationInFrames={180} fps={30} width={1920} height={1080} />
        <Composition id="Test-Diagrams" component={DiagramGallery} durationInFrames={DIAGRAM_GALLERY_FRAMES} fps={30} width={1920} height={1080} />
        <Composition id="Test-Effects" component={EffectGallery} durationInFrames={180} fps={30} width={1920} height={1080} />
      </Folder>
    </>
  );
};
